"""Dodo existing-subscription plan-change regression tests (fix for a
confirmed production double-billing bug).

Root cause: a workspace with an existing, active Dodo subscription that
clicked another paid plan (Pro -> Team or Team -> Pro) was routed through
the exact same ``adapter.create_checkout`` path a brand-new Free
workspace uses — creating a SECOND, independent Dodo subscription while
the original stayed active and billable. Confirmed via the real Dodo
dashboard: both a Pro subscription ($10/mo) and a new Team subscription
($30/mo) were simultaneously Active for one workspace after a Pro ->
Team "upgrade".

Fix: ``_create_plan_checkout`` (app/routers/billing.py) now checks for an
existing, live ``NormalizedSubscription`` row BEFORE ever calling
``adapter.create_checkout``. If that row belongs to Dodo and is in a live
status, the request is routed to ``_change_existing_dodo_plan``, which
calls the new ``DodoBillingAdapter.change_subscription_plan`` — built on
the already-verified ``POST /subscriptions/{id}/change-plan`` endpoint
(the same one ``update_subscription`` already used for Team seat
changes) — against the EXISTING subscription ID. No new Dodo subscription
is ever created for an existing Dodo customer.

Router-level tests here monkeypatch ``get_adapter_for_provider`` with a
recording fake adapter — no real or mocked HTTP call is made, and
therefore no live or Test Mode Dodo API traffic is generated by this
file at all. Adapter-payload-level tests (proration, product_id, addon
handling) reuse the exact ``httpx.MockTransport`` pattern already
established in ``test_commercial_dodo_checkout.py``.
"""

