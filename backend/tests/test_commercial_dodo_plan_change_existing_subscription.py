class TestDbRowNotMutatedDirectlyByRouter:
    """The webhook remains the single source of truth for plan_id/status —
    the router only ever calls the Dodo-side API; it never mutates the
    NormalizedSubscription row itself (that would be a second, unverified
    source of truth for entitlements)."""

    def test_row_plan_id_unchanged_until_webhook_arrives(self, monkeypatch, workspace, db_session, test_user):
        sub = _dodo_row(db_session, workspace, plan_id="pro", status="active", subscription_id="sub_pro_1")
        _call_create_plan_checkout(monkeypatch, PlanId.TEAM, workspace, db_session, test_user)
        db_session.refresh(sub)
        assert sub.plan_id == "pro"  # unchanged locally; webhook will update it
