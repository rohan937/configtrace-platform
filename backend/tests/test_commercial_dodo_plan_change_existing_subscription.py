# ── Adapter-level payload tests (mocked HTTP, no router involved) ──────────


def _mapping() -> DodoCatalogMapping:
    return DodoCatalogMapping(
        environment="test", pro_product_id="prod_pro_test",
        team_product_id="prod_team_test", team_seat_addon_id="addon_seat_test",
    )


def _adapter(handler) -> DodoBillingAdapter:
    transport = httpx.MockTransport(handler)
    client = DodoAPIClient(DodoClientConfig(environment="test", api_key="apikey_test_dummy"), transport=transport)
    return DodoBillingAdapter(_mapping(), client)


def _sub_ref(external_id: str) -> BillingProviderReference:
    return BillingProviderReference(
        provider=BillingProvider.DODO, object_type=__import__("app.billing.enums", fromlist=["ObjectType"]).ObjectType.SUBSCRIPTION,
        external_id=external_id, workspace_id=uuid.uuid4(),
    )


class TestChangeSubscriptionPlanPayload:
    def test_pro_to_team_calls_change_plan_not_checkout(self):
        calls = {"checkout": 0, "change_plan": []}

        def handler(request: httpx.Request) -> httpx.Response:
            calls["checkout"] += 1
            return httpx.Response(200, json={})

        adapter = _adapter(handler)

        def fake_change_plan(subscription_id, *, body, correlation_id=None):
            calls["change_plan"].append((subscription_id, body))
            return {"subscription_id": subscription_id}

        adapter._client.change_plan = fake_change_plan  # type: ignore[method-assign]

        result = adapter.change_subscription_plan(
            subscription_reference=_sub_ref("sub_pro_1"), target_plan_id=PlanId.TEAM, billable_seat_count=1,
        )
        assert calls["checkout"] == 0
        assert len(calls["change_plan"]) == 1
        sub_id, body = calls["change_plan"][0]
        assert sub_id == "sub_pro_1"  # SAME subscription ID — never a new one
        assert body["product_id"] == "prod_team_test"
        assert isinstance(result, ProviderOperationResult)
        assert result.state == "ok"

    def test_team_to_pro_calls_change_plan_with_pro_product(self):
        def handler(request: httpx.Request) -> httpx.Response:
            return httpx.Response(200, json={})

        adapter = _adapter(handler)
        captured = {}

        def fake_change_plan(subscription_id, *, body, correlation_id=None):
            captured["sub_id"] = subscription_id
            captured["body"] = body
            return {}

        adapter._client.change_plan = fake_change_plan  # type: ignore[method-assign]

        adapter.change_subscription_plan(
            subscription_reference=_sub_ref("sub_team_1"), target_plan_id=PlanId.PRO, billable_seat_count=25,
        )
        assert captured["sub_id"] == "sub_team_1"
        assert captured["body"]["product_id"] == "prod_pro_test"
        assert captured["body"]["addons"] == []  # Pro never carries the Team seat add-on

    def test_upgrade_to_team_uses_prorated_immediately(self):
        def handler(request: httpx.Request) -> httpx.Response:
            return httpx.Response(200, json={})

        adapter = _adapter(handler)
        captured = {}
        adapter._client.change_plan = lambda sub_id, *, body, correlation_id=None: captured.update(body=body) or {}  # type: ignore

        adapter.change_subscription_plan(
            subscription_reference=_sub_ref("sub_1"), target_plan_id=PlanId.TEAM, billable_seat_count=1,
        )
        assert captured["body"]["proration_billing_mode"] == "prorated_immediately"

    def test_downgrade_to_pro_uses_do_not_bill(self):
        def handler(request: httpx.Request) -> httpx.Response:
            return httpx.Response(200, json={})

        adapter = _adapter(handler)
        captured = {}
        adapter._client.change_plan = lambda sub_id, *, body, correlation_id=None: captured.update(body=body) or {}  # type: ignore

        adapter.change_subscription_plan(
            subscription_reference=_sub_ref("sub_1"), target_plan_id=PlanId.PRO, billable_seat_count=1,
        )
        assert captured["body"]["proration_billing_mode"] == "do_not_bill"

    def test_team_seat_addon_included_when_over_20_members(self):
        def handler(request: httpx.Request) -> httpx.Response:
            return httpx.Response(200, json={})

        adapter = _adapter(handler)
        captured = {}
        adapter._client.change_plan = lambda sub_id, *, body, correlation_id=None: captured.update(body=body) or {}  # type: ignore

        adapter.change_subscription_plan(
            subscription_reference=_sub_ref("sub_1"), target_plan_id=PlanId.TEAM, billable_seat_count=25,
        )
        assert captured["body"]["addons"] == [{"addon_id": "addon_seat_test", "quantity": 5}]

    def test_unsupported_plan_raises_not_guessed(self):
        def handler(request: httpx.Request) -> httpx.Response:
            return httpx.Response(200, json={})

        adapter = _adapter(handler)  # fully configured mapping — FREE simply has no product_id
        with pytest.raises(DodoUnsupportedPlanError):
            adapter.change_subscription_plan(
                subscription_reference=_sub_ref("sub_1"), target_plan_id=PlanId.FREE, billable_seat_count=1,
            )


# ── Router-level tests (fake adapter, no HTTP at all) ───────────────────────


class _FakeDodoAdapter:
    """Records calls; never performs I/O. Used to prove the router picks
    the plan-change path instead of create_checkout, without depending on
    real or mocked Dodo HTTP traffic."""

    def __init__(self):
        self.create_checkout_calls: list = []
        self.change_subscription_plan_calls: list = []

    def create_checkout(self, request):
        self.create_checkout_calls.append(request)
        from app.billing.provider import CheckoutResponse

        return CheckoutResponse(
            provider=BillingProvider.DODO, checkout_url="https://test.checkout.dodopayments.com/new",
            external_reference="cks_new",
        )

    def change_subscription_plan(self, *, subscription_reference, target_plan_id, billable_seat_count):
        self.change_subscription_plan_calls.append((subscription_reference, target_plan_id, billable_seat_count))
        return ProviderOperationResult(state="ok", detail="changed")


@pytest.fixture
def workspace(db_session, test_user):
    ws = Workspace(name=f"dodo-planchange-{uuid.uuid4().hex[:8]}", created_by_user_id=test_user.id)
    db_session.add(ws)
    db_session.flush()
    db_session.add(WorkspaceMember(workspace_id=ws.id, user_id=test_user.id, role="owner"))
    db_session.commit()
    db_session.refresh(ws)
    yield ws
    db_session.query(NormalizedSubscription).filter(NormalizedSubscription.workspace_id == ws.id).delete()
    db_session.commit()


def _dodo_row(db_session, workspace, *, plan_id="pro", status="active", subscription_id="sub_pro_1"):
    sub = NormalizedSubscription(
        workspace_id=workspace.id, provider="dodo", plan_id=plan_id, status=status,
        provider_customer_reference="cus_1", provider_subscription_reference=subscription_id,
        billable_seats=0, additional_seat_quantity=0,
    )
    db_session.add(sub)
    db_session.commit()
    db_session.refresh(sub)
    return sub


def _call_create_plan_checkout(monkeypatch, plan_id, workspace, db_session, test_user, fake_adapter=None):
    from app.routers import billing as billing_router

    adapter = fake_adapter if fake_adapter is not None else _FakeDodoAdapter()
    monkeypatch.setattr(billing_router, "get_adapter_for_provider", lambda provider, db: adapter)
    monkeypatch.setattr(billing_router, "provider_for_checkout", lambda workspace_id, db: BillingProvider.DODO)
    monkeypatch.setattr(billing_router, "dodo_pilot_override_active", lambda workspace_id: False)
    result = billing_router._create_plan_checkout(plan_id, workspace.id, db_session, test_user)
    return result, adapter


class TestFreeWorkspaceStillCreatesCheckout:
    def test_free_to_pro_creates_checkout(self, monkeypatch, workspace, db_session, test_user):
        result, adapter = _call_create_plan_checkout(monkeypatch, PlanId.PRO, workspace, db_session, test_user)
